// Package splitter 提供文档文本切片（Chunking）能力。
// 作用：把长文档切成适合向量化（Embedding）与检索的片段。
// 切片质量直接影响 RAG 检索效果：切太粗检索不准，切太碎语义不完整。
package splitter

// ============ 切片策略常量 ============
//
// 目标：把长文本切成大小合适、语义完整的片段。
//
// 设计考虑（对应"为什么要有重叠"）：
//   - 若恰好在一个句子中间切开，两边片段各自语义都不完整，检索时难以命中正确的上下文。
//   - 通过相邻切片之间保留一部分重叠字句，既保证每个切片上下文完整，
//     又让被切断的语义边界能在至少一个切片里保持连续。
//
// 参数取值依据：
//   - ChunkSize: 当前向量模型对短文本检索友好；中文 500~800 字符兼顾语义完整与精度。
//   - OverlapSize: 50~100 字符，确保重叠段覆盖到前一片段的尾部语意，防止关键句被斩断。
//
// 策略：优先按段落（空行分隔）切分；若某一段仍超过 ChunkSize，再按字符硬切。

// ChunkSize 单个切片的目标大小（字符数）。
// 建议 500~800（中文场景）。取 600 作为平衡点。
const ChunkSize = 600

// OverlapSize 相邻切片之间的重叠大小（字符数）。
// 建议 50~100。取 80：足够覆盖被切断的句尾语义，又不过度冗余。
const OverlapSize = 80

// ============ 策略说明（供文档/注释引用） ============

// strategyNote 记录切片策略的取舍要点，方便后续维护者理解为什么这样做。
// 这些内容不参与逻辑，仅作为包内设计文档。
var strategyNote = `
切片策略：
1. 切分粒度：目标片段 ChunkSize=600 字符，重叠 OverlapSize=80 字符。
2. 段落优先：先按段落（连续非空行）切分，保持段落天然语义单元。
3. 硬切兜底：单段超过 ChunkSize 时，按"超过点向前回找最近分隔点"，尽量在
   句号/换行等自然边界断开；实在没有才按字符数硬切。
4. 重叠补全：切片滑动时，每片头部拼接上一片尾部 OverlapSize 字符，
   确保跨片语义在至少一个完整切块中出现，避免检索时上下文被切断。
`
